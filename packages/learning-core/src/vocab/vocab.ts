export interface VocabWord {
  /** stable id, also used as the flashcard key ("v:" + id) */
  id: string;
  category: CategoryId;
  /** picture: a Unicode emoji (no image licences, works offline) */
  emoji: string;
  /** Arabic with vowel marks (harakat) */
  ar: string;
  bn: string;
  en: string;
  /** false when no single emoji shows the meaning (phrases, days): picture games skip these words */
  visual: boolean;
}

/** Categories whose words have no distinct picture. */
const NO_PICTURE: ReadonlySet<CategoryId> = new Set(['phrases', 'days']);

/**
 * Everyday Arabic words and phrases, written by hand: DRAFT. Every Arabic spelling and Bangla meaning should be reviewed by a
 * native Arabic speaker and a Bangla speaker before release (docs/vocabulary-review.md).
 */
function V(category: CategoryId, slug: string, emoji: string, ar: string, bn: string, en: string): VocabWord {
  return { id: `${category}.${slug}`, category, emoji, ar, bn, en, visual: !NO_PICTURE.has(category) };
}

